# 나이 입력받고,
# 성인인지 아닌지 판단 (20살 이상이면 성인)
# 미성년자의 경우, "미성년자" 출력
# 미성년자의 경우 미취학(0~7),초등(8~13),중등(14~16),고등(17~19) 분류
# e.g.
# 나이가 15살인 경우 "중등" 출력
# 나이가 20살인 경우 "성인" 출력
# 나이가 2살인 경우 "미취학" 출력

age = int(input("몇살이에요?"))

if age >= 20:
    print("성인")
else:
    print ("미성년자")
    if age < 8:
        print("미취학")
    elif age < 14:
        print("초등")
    elif age < 17:
        print("중등")
    else:
        print("고등")